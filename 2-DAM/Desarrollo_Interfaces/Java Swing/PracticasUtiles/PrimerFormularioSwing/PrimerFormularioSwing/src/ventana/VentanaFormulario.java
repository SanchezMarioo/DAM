    private void btnGenerarAlumnoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarAlumnoActionPerformed
        // TODO add your handling code here:
        String nombre = txfNombre.getText().trim();
        String apellidos = txfApellidos.getText().trim();
        String nif = ftfNIF.getText().trim();
        String direccion = txfDireccion.getText().trim();
        String telefono = ftfTelefono.getText().trim();
        String email = txfEmail.getText().trim();
        String ciclo = cbxCiclo.getSelectedItem() != null ? cbxCiclo.getSelectedItem().toString() : "";
        String fechaNac = spnFechaNac.getValue() != null ? spnFechaNac.getValue().toString() : "";

        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Introduce al menos el nombre del alumno.");
            return;
        }

        // Solo el radiobutton seleccionado
        String turno = "";
        if (rbtMatutino.isSelected()) {
            turno = rbtMatutino.getText();
        } else if (rbtVespertino.isSelected()) {
            turno = rbtVespertino.getText();
        }

        // Solo los checkboxes seleccionados
        java.util.List<String> extraescolares = new java.util.ArrayList<>();
        if (chkFutbol.isSelected()) {
            extraescolares.add(chkFutbol.getText());
        }
        if (chkBaloncesto.isSelected()) {
            extraescolares.add(chkBaloncesto.getText());
        }
        if (chkMusica.isSelected()) {
            extraescolares.add(chkMusica.getText());
        }
        if (chkAjedrez.isSelected()) {
            extraescolares.add(chkAjedrez.getText());
        }

        StringBuilder contenido = new StringBuilder();
        contenido.append("Nombre: ").append(nombre).append(System.lineSeparator());
        contenido.append("Apellidos: ").append(apellidos).append(System.lineSeparator());
        contenido.append("NIF: ").append(nif).append(System.lineSeparator());
        contenido.append("Fecha nac.: ").append(fechaNac).append(System.lineSeparator());
        contenido.append("Direccion: ").append(direccion).append(System.lineSeparator());
        contenido.append("Telefono: ").append(telefono).append(System.lineSeparator());
        contenido.append("Email: ").append(email).append(System.lineSeparator());
        contenido.append("Ciclo: ").append(ciclo).append(System.lineSeparator());

        if (!turno.isEmpty()) {
            contenido.append("Turno: ").append(turno).append(System.lineSeparator());
        }
        if (!extraescolares.isEmpty()) {
            contenido.append("Extraescolares: ").append(String.join(", ", extraescolares)).append(System.lineSeparator());
        }
        contenido.append("----------------------------------------").append(System.lineSeparator());

        try (java.io.BufferedWriter writer = new java.io.BufferedWriter(
                new java.io.OutputStreamWriter(
                        new java.io.FileOutputStream("matriculas.txt", true),
                        java.nio.charset.StandardCharsets.UTF_8))) {
            writer.write(contenido.toString());
            javax.swing.JOptionPane.showMessageDialog(this, "Alumno añadido a matriculas.txt");
        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al escribir en matriculas.txt: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnGenerarAlumnoActionPerformed

