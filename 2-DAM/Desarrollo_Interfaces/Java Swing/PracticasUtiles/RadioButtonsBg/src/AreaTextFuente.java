    private void jCBNegritaItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCBNegritaItemStateChanged
        // TODO add your handling code here:
        if (jCBNegrita.isSelected()) {
            jTextArea1.setFont(jTextArea1.getFont().deriveFont(Font.BOLD));
        } else {
            jTextArea1.setFont(jTextArea1.getFont().deriveFont(Font.PLAIN));

        }
    }//GEN-LAST:event_jCBNegritaItemStateChanged

    private void jCBCursivaItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCBCursivaItemStateChanged
        // TODO add your handling code here:
        if (jCBCursiva.isSelected()) {
            jTextArea1.setFont(jTextArea1.getFont().deriveFont(Font.ITALIC));
        } else {
            jTextArea1.setFont(jTextArea1.getFont().deriveFont(Font.PLAIN));
        }
    }//GEN-LAST:event_jCBCursivaItemStateChanged

    private void jCBInvertirItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCBInvertirItemStateChanged
        // TODO add your handling code here:
        if (jCBInvertir.isSelected()) {
            jTextArea1.setBackground(fuenteOriginal);
            jTextArea1.setForeground(fondoOriginal);
        } else {
            jTextArea1.setBackground(fondoOriginal);
            jTextArea1.setForeground(fuenteOriginal);
        }
    }//GEN-LAST:event_jCBInvertirItemStateChanged

