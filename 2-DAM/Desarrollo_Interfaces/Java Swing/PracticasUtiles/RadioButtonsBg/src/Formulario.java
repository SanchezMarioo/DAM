    private ArrayList<String> cogerDatosFormulario() {
        System.out.println("Entra sd");
        ArrayList<String> textos = new ArrayList();
        for (Component c : this.getContentPane().getComponents()) {
            if (c instanceof JTextField jTextField) {
                textos.add(jTextField.getText());
            }
        }
        return textos;
    }

    private void crearArchivoConDatos(File file, ArrayList<String> datos) {
        try {
            file.createNewFile();
        } catch (IOException ex) {
            System.getLogger(Formulario.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

        for (String dato : datos) {

            System.out.println(dato);
            try (FileWriter escritor = new FileWriter(file, true)) {
                escritor.write(dato);
                escritor.write(" | ");
            } catch (IOException ex) {
                System.getLogger(Formulario.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }

        }
        try (FileWriter escritor = new FileWriter(file, true)) {
            escritor.write("\n");
        } catch (IOException ex) {
            System.getLogger(Formulario.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

    }

