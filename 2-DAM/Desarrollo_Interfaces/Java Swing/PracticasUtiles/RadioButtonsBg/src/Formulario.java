    private void jBotonArchivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBotonArchivoActionPerformed
        // TODO add your handling code here:
        ArrayList<String> datos = cogerDatosFormulario();
        JFileChooser fileChooser = new JFileChooser();
        int eleccionUsuario = fileChooser.showOpenDialog(this);
        if (eleccionUsuario == JFileChooser.APPROVE_OPTION) {
            File fichero = fileChooser.getSelectedFile();
            crearArchivoConDatos(fichero, datos);
        }

    }//GEN-LAST:event_jBotonArchivoActionPerformed

