    private void chbNegritaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chbNegritaActionPerformed
        // TODO add your handling code here:
        Font fuente = txaAreaEscribir.getFont();
        int estilo = Font.PLAIN;

        if (chbNegrita.isSelected()) {
            estilo |= Font.BOLD;
        }

        if (chbCursiva.isSelected()) {
            estilo |= Font.ITALIC;
        }

        txaAreaEscribir.setFont(fuente.deriveFont(estilo));
    }//GEN-LAST:event_chbNegritaActionPerformed

